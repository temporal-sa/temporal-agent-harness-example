#!/usr/bin/env node
// Generates src/generated/ from the agents' JSON Schema (P3 step 3.0, PM decision 3).
//
//   npm run gen            (from simple_chat_agent/web)
//   make gen               (from the repo root)
//
// 1. `temporal-agent-harness schema <module:Class>` (the harness CLI in the repo's .venv)
//    prints each agent's init data, @agent.accepts handlers and agent.state(...) declarations
//    as JSON Schema. Raw output is kept in src/generated/schema/ so diffs show schema changes.
// 2. json-schema-to-typescript (pinned devDependency) turns the merged $defs into models.ts.
// 3. agents.ts maps each agent's handlers (input, output, mid-turn policy) and states to those
//    models.
//
// The output is plain TypeScript with no runtime imports. Never edit it by hand; rerun this.
//
// Importing the agent modules builds the worker's model registry, which needs a provider key
// to be present (never used: nothing is called). The child process gets placeholder keys and
// none of this shell's real ones.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = resolve(HERE, "..");
const REPO = resolve(WEB, "../..");
const OUT = join(WEB, "src", "generated");
const SCHEMA_OUT = join(OUT, "schema");

// The agents the product view talks to. `file` names the raw schema file.
const AGENTS = [
  { name: "CodingAgent", target: "simple_chat_agent.agent.workflow:CodingAgent", file: "coding-agent" },
  { name: "ExplorerAgent", target: "simple_chat_agent.agent.subagents:ExplorerAgent", file: "explorer-agent" },
  { name: "ReviewerAgent", target: "simple_chat_agent.agent.subagents:ReviewerAgent", file: "reviewer-agent" },
];

const BANNER = [
  "/* eslint-disable */",
  "// GENERATED by simple_chat_agent/web/scripts/gen.mjs from `temporal-agent-harness schema`.",
  "// Do not edit by hand: change the Python models and run `make gen`.",
].join("\n");

function python() {
  if (process.env.PYTHON) return process.env.PYTHON;
  const venv = join(REPO, ".venv", "bin", "python");
  return existsSync(venv) ? venv : "python3";
}

function schemaEnv() {
  // A minimal environment: no inherited secrets, placeholder provider keys so the worker's
  // model registry imports. No network call is made with them.
  const env = {
    PATH: process.env.PATH ?? "",
    HOME: process.env.HOME ?? "",
    PYTHONDONTWRITEBYTECODE: "1",
    PYTHONPATH: REPO,
    ANTHROPIC_API_KEY: "schema-generation-only",
    OPENAI_API_KEY: "schema-generation-only",
    GEMINI_API_KEY: "schema-generation-only",
  };
  for (const key of ["LANG", "LC_ALL", "TMPDIR", "VIRTUAL_ENV"]) {
    if (process.env[key]) env[key] = process.env[key];
  }
  return env;
}

function agentSchema(target) {
  const result = spawnSync(
    python(),
    ["-m", "temporal_agent_harness.web.cli", "schema", target],
    { cwd: REPO, env: schemaEnv(), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stderr ?? "");
    throw new Error(`temporal-agent-harness schema ${target} failed (exit ${result.status})`);
  }
  return JSON.parse(result.stdout);
}

// "Name-Input" -> "NameInput", "_WorkflowStreamWireItem" -> "WorkflowStreamWireItem".
function typeName(key) {
  return key.replace(/[^A-Za-z0-9]+/g, " ").trim().split(" ").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
}

function refName(ref) {
  const prefix = "#/$defs/";
  if (typeof ref !== "string" || !ref.startsWith(prefix)) throw new Error(`unexpected $ref ${ref}`);
  return ref.slice(prefix.length);
}

// Drop pydantic's per-property titles (json-schema-to-typescript would turn each into its own
// alias, e.g. `type Text = string`) and point refs at `definitions`.
function clean(node) {
  if (Array.isArray(node)) return node.map(clean);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    // The `title` keyword is a string; a property that happens to be named `title` is a schema.
    if (key === "title" && typeof value === "string") continue;
    if (key === "$ref") {
      out.$ref = `#/definitions/${typeName(refName(value))}`;
      continue;
    }
    out[key] = clean(value);
  }
  return out;
}

function mergeDefs(schemas) {
  const merged = {};
  const origin = {};
  for (const [agent, schema] of schemas) {
    for (const [key, def] of Object.entries(schema.$defs ?? {})) {
      const name = typeName(key);
      const body = JSON.stringify(def);
      if (merged[name] !== undefined && JSON.stringify(merged[name].raw) !== body) {
        throw new Error(`${name} differs between ${origin[name]} and ${agent}; rename one of the models`);
      }
      merged[name] = { raw: def };
      origin[name] = origin[name] ?? agent;
    }
  }
  const definitions = {};
  for (const name of Object.keys(merged).sort()) {
    definitions[name] = { ...clean(merged[name].raw), title: name };
  }
  return definitions;
}

function quote(text) {
  return JSON.stringify(text ?? "");
}

function agentsModule(schemas) {
  const used = new Set();
  const lines = [BANNER, ""];
  const body = [];
  for (const [agent, schema] of schemas) {
    const handlers = Object.entries(schema.handlers);
    const states = Object.entries(schema.states);
    const init = schema.init_data ? typeName(refName(schema.init_data.data.$ref)) : null;
    if (init) used.add(init);

    body.push(`/** ${agent}: the workflow type \`${schema.agent}\` (${schema.source}). */`);
    body.push(`export interface ${agent}Handlers {`);
    for (const [name, h] of handlers) {
      const input = typeName(refName(h.input.$ref));
      const output = typeName(refName(h.output.$ref));
      used.add(input);
      used.add(output);
      body.push(`  /** ${h.description} (mid-turn: ${h.mid_turn}) */`);
      body.push(`  ${name}: { input: ${input}; output: ${output}; midTurn: ${quote(h.mid_turn)} };`);
    }
    body.push("}", "");
    body.push(`export type ${agent}HandlerName = keyof ${agent}Handlers;`);
    body.push(`export type ${agent}Input<H extends ${agent}HandlerName> = ${agent}Handlers[H]["input"];`);
    body.push(`export type ${agent}Output<H extends ${agent}HandlerName> = ${agent}Handlers[H]["output"];`);
    body.push("");
    body.push(`export const ${agent}HandlerInfo = {`);
    for (const [name, h] of handlers) {
      body.push(`  ${name}: { description: ${quote(h.description)}, midTurn: ${quote(h.mid_turn)} },`);
    }
    body.push(`} as const satisfies Record<${agent}HandlerName, { description: string; midTurn: string }>;`, "");

    body.push(`/** States the agent publishes with agent.state(...), by state id. */`);
    if (states.length === 0) {
      body.push(`export type ${agent}States = Record<string, never>;`);
    } else {
      body.push(`export interface ${agent}States {`);
      for (const [id, ref] of states) {
        const t = typeName(refName(ref.$ref));
        used.add(t);
        body.push(`  ${id}: ${t};`);
      }
      body.push("}");
    }
    body.push(`export type ${agent}StateId = keyof ${agent}States;`);
    body.push(`export const ${agent}StateIds = ${JSON.stringify(states.map(([id]) => id))} as const;`);
    body.push(`/** The init data a session of this agent starts with${schema.init_data?.required ? " (required)" : ""}. */`);
    body.push(`export type ${agent}InitData = ${init ?? "never"};`, "");
  }
  lines.push(`import type { ${[...used].sort().join(", ")} } from "./models";`, "", ...body);
  return lines.join("\n");
}

async function main() {
  // Pinned devDependency of simple_chat_agent/web. GEN_JSON2TS overrides the module path for a
  // bootstrap run before `npm ci` has installed it.
  const { compile } = await import(process.env.GEN_JSON2TS ?? "json-schema-to-typescript");

  const schemas = AGENTS.map((a) => [a.name, agentSchema(a.target)]);

  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(SCHEMA_OUT, { recursive: true });
  for (const [i, [, schema]] of schemas.entries()) {
    writeFileSync(join(SCHEMA_OUT, `${AGENTS[i].file}.schema.json`), JSON.stringify(schema, null, 2) + "\n");
  }

  const definitions = mergeDefs(schemas);
  // The root is only a carrier for `definitions`; its own (empty) type is dropped below.
  const models = await compile(
    { title: "GeneratedRoot", type: "object", additionalProperties: false, properties: {}, definitions },
    "GeneratedRoot",
    {
      bannerComment: BANNER,
      unreachableDefinitions: true,
      additionalProperties: false,
      strictIndexSignatures: true,
      enableConstEnums: false,
      format: true,
      style: { singleQuote: false, semi: true, printWidth: 100 },
    },
  );
  const withoutRoot = models
    .replace(/export interface GeneratedRoot \{\}\n*/, "")
    .replace(/ \* This \w+ was referenced by `GeneratedRoot`'s JSON-Schema\n \* via the `definition` "\w+"\.\n/g, "")
    .replace(/\/\*\*\n \*\/\n/g, "")
    .replace(/\n \*\n \*\//g, "\n */");
  if (withoutRoot.includes("GeneratedRoot")) throw new Error("couldn't drop the carrier root type");
  writeFileSync(join(OUT, "models.ts"), withoutRoot);
  writeFileSync(join(OUT, "agents.ts"), agentsModule(schemas));
  writeFileSync(
    join(OUT, "index.ts"),
    [BANNER, "", 'export * from "./models";', 'export * from "./agents";', ""].join("\n"),
  );
  const files = readdirSync(OUT, { recursive: true }).filter((f) => !String(f).endsWith("schema"));
  process.stdout.write(`generated ${files.length} files in ${OUT}\n`);
}

main().catch((err) => {
  process.stderr.write(`gen: ${err.message}\n`);
  process.exit(1);
});
